public class CarvedGourdBlock extends HorizontalDirectionalBlock implements Equipable {
    public static final MapCodec<CarvedGourdBlock> CODEC = simpleCodec(CarvedGourdBlock::new);
    public static final DirectionProperty FACING = HorizontalDirectionalBlock.FACING;

    public CarvedGourdBlock(Properties properties) {
        super(properties);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        return this.defaultBlockState().setValue(FACING, context.getHorizontalDirection().getOpposite());
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING);
    }

    @Override
    public MapCodec<CarvedGourdBlock> codec() {
        return CODEC;
    }

    @Override
    public EquipmentSlot getEquipmentSlot() {
        return EquipmentSlot.HEAD;
    }
}
